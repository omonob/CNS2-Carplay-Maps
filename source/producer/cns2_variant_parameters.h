#ifndef CNS2_VARIANT_PARAMETERS_H
#define CNS2_VARIANT_PARAMETERS_H
#ifndef CNS2_DISPLAY_FPS
#define CNS2_DISPLAY_FPS 40
#endif
#ifndef CNS2_DISPLAY_WIDTH
#define CNS2_DISPLAY_WIDTH 1010
#define CNS2_DISPLAY_HEIGHT 376
#define CNS2_PHYSICAL_WIDTH 202
#define CNS2_PHYSICAL_HEIGHT 75
#define CNS2_SAFE_X 202
#define CNS2_SAFE_Y 16
#define CNS2_SAFE_WIDTH 606
#define CNS2_SAFE_HEIGHT 344
#define CNS2_NAV_X 122
#endif
#if CNS2_DISPLAY_FPS < 30 || CNS2_DISPLAY_FPS > 80 || CNS2_DISPLAY_FPS % 10
#error Invalid CNS2 V43 FPS
#endif
#if CNS2_SAFE_X < 0 || CNS2_SAFE_Y < 0 || CNS2_NAV_X < 0 || \
    CNS2_SAFE_X + CNS2_SAFE_WIDTH > CNS2_DISPLAY_WIDTH || \
    CNS2_NAV_X + CNS2_SAFE_WIDTH > CNS2_DISPLAY_WIDTH || \
    CNS2_SAFE_Y + CNS2_SAFE_HEIGHT > CNS2_DISPLAY_HEIGHT
#error Invalid CNS2 V43 safe area
#endif
#endif
